# --- Database -------------------------------------------------------------
# postgis://... selects the PostGIS backend. Without DATABASE_URL we fall back
# to SQLite so the non-spatial parts of the app can run before PostGIS exists.
if env("DATABASE_URL", default=""):
    DATABASES = {"default": env.db("DATABASE_URL")}
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }

USE_GIS = DATABASES["default"]["ENGINE"] == "django.contrib.gis.db.backends.postgis"

# GeoDjango on Windows needs explicit paths to the GDAL/GEOS DLLs.
GDAL_LIBRARY_PATH = env("GDAL_LIBRARY_PATH", default=None)
GEOS_LIBRARY_PATH = env("GEOS_LIBRARY_PATH", default=None)

